/**
 * Looks up locality in dictionary and resolves district & state
 */
export function findLocationByLocality(localityStr) {
  if (!localityStr || typeof localityStr !== 'string') return null;
  const key = localityStr.toLowerCase().trim();
  if (CLIENT_LOCATION_LOOKUP[key]) {
    return {
      name: localityStr,
      ...CLIENT_LOCATION_LOOKUP[key]
    };
  }
  const match = Object.keys(CLIENT_LOCATION_LOOKUP).find(
    (k) => key.includes(k) || k.includes(key)
  );
  if (match) {
    return {
      name: match.charAt(0).toUpperCase() + match.slice(1),
      ...CLIENT_LOCATION_LOOKUP[match]
    };
  }
  return null;
}
